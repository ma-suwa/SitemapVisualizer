function drawPatternA(data) {
  const width = document.getElementById('svg-container').clientWidth || window.innerWidth;
  const depth = PARAMS.Depth;

  const root = d3.hierarchy(data);
  const dx = PARAMS.Height;
  const dy = width / (root.height + 1);
  d3.tree().nodeSize([dx, dy])(root);

  let x0 = Infinity, x1 = -Infinity;
  root.each(d => {
    if (d.depth <= depth) { if (d.x > x1) x1 = d.x; if (d.x < x0) x0 = d.x; }
  });
  const svgH = x1 - x0 + dx * 3;

  const svg = d3.select('#svg-container').append('svg')
    .attr('width', width).attr('height', svgH)
    .attr('viewBox', [-dy / 3, x0 - dx * 2, width, svgH])
    .attr('preserveAspectRatio', 'xMinYMid meet');

  let nid = 0;
  root.x0 = 0;
  root.y0 = 0;

  function update(src) {
    const nodes = root.descendants().filter(d => d.depth <= depth);
    const links = root.links().filter(d => d.target.depth <= depth);

    const node = svg.selectAll('g.node').data(nodes, d => d.id || (d.id = ++nid));

    const enter = node.enter().append('g').attr('class', 'node')
      .attr('transform', () => `translate(${src.y0 ?? src.y},${src.x0 ?? src.x})`)
      .on('click', function (d) {
        if (d.children) { d._children = d.children; d.children = null; }
        else { d.children = d._children; d._children = null; }
        update(d);
      });

    enter.append('circle').attr('r', 4).attr('fill', d => d._children ? '#000' : '#999');
    enter.append('text')
      .attr('dy', '0.31em')
      .attr('x', d => (d.children || d._children) ? -6 : 6)
      .attr('text-anchor', d => (d.children || d._children) ? 'end' : 'start')
      .text(d => d.data.label || d.data.name)
      .attr('stroke', 'white').attr('stroke-width', 3).attr('paint-order', 'stroke');

    const upd = enter.merge(node);
    upd.transition().duration(200).attr('transform', d => `translate(${d.y},${d.x})`);
    upd.select('circle').attr('r', 5).attr('fill', d => d._children ? '#000' : '#999');
    upd.select('text').style('fill-opacity', 1).style('font-size', '0.7em');
    node.exit().transition().duration(200)
      .attr('transform', () => `translate(${src.y},${src.x})`).remove();

    const link = svg.selectAll('path.link').data(links, d => d.target.id);
    link.enter().insert('path', 'g').attr('class', 'link')
      .attr('d', d3.linkHorizontal().x(() => src.y0 ?? src.y).y(() => src.x0 ?? src.x))
      .merge(link).transition().duration(200)
      .attr('d', d3.linkHorizontal().x(d => d.y).y(d => d.x));
    link.exit().transition().duration(200)
      .attr('d', d3.linkHorizontal().x(() => src.y).y(() => src.x)).remove();

    nodes.forEach(d => { d.x0 = d.x; d.y0 = d.y; });
  }

  update(root);
}

