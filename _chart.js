function calcNodeBounds(nodes) {
  let xMin = Infinity, xMax = -Infinity, yMax = 0;
  nodes.forEach(d => {
    if (d.x < xMin) xMin = d.x;
    if (d.x > xMax) xMax = d.x;
    if (d.y > yMax) yMax = d.y;
  });
  return { xMin, xMax, yMax };
}

